using System.Text;
using Norse.Abstractions.Emit;

namespace Norse.Infrastructure.Web.Server.Generator.Xml;

/// <summary>
///     Emits the one-per-host-compilation registration summary (Task 8): a static <c>Build()</c> that
///     lists every distinct generated <c>{Contract}XmlShape</c> class — the exact same deduplicated set
///     <see cref="XmlShapeGenerator" /> already computed for its own per-shape emission loop. This emitter
///     carries no dedup logic of its own; the closure walk's dedup (Task 6, <c>GroupBy(TypeName).Last()</c>)
///     is the single source of truth for "one shape class per distinct contract type," so duplicate
///     registration is impossible by construction, not by a second check here.
/// </summary>
static class RegistrationEmitter
{
	const string XmlNs = "global::Norse.Infrastructure.Web.Server.Xml";

	/// <summary>
	///     Emits <c>NorseXmlShapeRegistration</c> for <paramref name="shapes" /> — called exactly once per host
	///     compilation, even when <paramref name="shapes" /> is empty (the host always calls <c>Build()</c> unconditionally).
	/// </summary>
	public static string Emit(string rootNamespace, IReadOnlyList<ShapeModel> shapes)
	{
		List<string> adds = [];
		foreach (var shape in shapes)
			adds.Add($"\t\tregistry.Add({WriterEmitter.ShortName(shape.TypeName)}XmlShape.Instance);");

		var addLines = adds.Count == 0 ?
			string.Empty :
			string.Join("\n", adds);

		StringBuilder sb = new();
		sb.AppendCSharp(
			$$"""
			// <auto-generated/>
			#nullable enable
			namespace {{rootNamespace}}.NorseXmlShapes;

			#pragma warning disable CS1591 // Generated Futhark XML shape registration: no XML doc comments.
			/// <summary>Generated by Norse.Infrastructure.Web.Server.Generator.Xml — lists every Futhark XML shape reachable from this compilation's facade controllers.</summary>
			internal static class NorseXmlShapeRegistration
			{
				public static {{XmlNs}}.XmlShapeRegistry Build()
				{
					var registry = new {{XmlNs}}.XmlShapeRegistry();
			{{addLines}}
					return registry;
				}
			}
			#pragma warning restore CS1591
			""");
		return sb.ToString();
	}

	/// <summary>
	///     Emits <c>NorseEnumNameRegistration</c> (Task 8): one <c>EnumNameTable</c> field per distinct
	///     enum type reachable from any shape's members, plus a <c>Build()</c> that lists them all — the
	///     mirror image of <see cref="Emit" /> above, one namespace, same host-compilation cardinality (called
	///     exactly once, even with zero enums). <see cref="WriterEmitter.EnumTableReference" /> is the one
	///     other place that knows this class's field-naming scheme (<see cref="WriterEmitter.SafeIdentifier" />
	///     plus the <c>Table</c> suffix) — both sides agree on a field name without either coordinating with
	///     the other beyond calling the same helper.
	/// </summary>
	public static string EmitEnumRegistration(string rootNamespace, IReadOnlyList<ShapeModel> shapes)
	{
		// One member per distinct enum type, first occurrence wins — every member the closure walk
		// records for a given enum type carries the same EnumValues (the enum's own defined members),
		// so which occurrence supplies the field's data is immaterial; only the enum type identity
		// (ScalarTypeName) determines dedup, mirroring XmlShapeGenerator's own shape-level dedup.
		var enumMembers = shapes
			.SelectMany(static s => s.Members)
			.Where(static m => m.EnumValues.Count > 0)
			.GroupBy(static m => m.ScalarTypeName, StringComparer.Ordinal)
			.Select(static g => g.First())
			.OrderBy(static m => m.ScalarTypeName, StringComparer.Ordinal)
			.ToList();

		List<string> fields = [];
		List<string> adds = [];
		foreach (var member in enumMembers)
		{
			var enumType = member.ScalarTypeName!;
			var fieldName = $"{WriterEmitter.SafeIdentifier(enumType)}Table";
			var typeName = WriterEmitter.ShortName(enumType);

			List<string> nameRows = [];
			List<string> values = [];
			foreach (var value in member.EnumValues)
			{
				nameRows.Add(WriterEmitter.NamesLiteral(value.WireNames));
				values.Add($"{value.Value}L");
			}

			fields.Add(
				$"\tpublic static readonly {XmlNs}.EnumNameTable {fieldName} = new(typeof({enumType}), {WriterEmitter.Quote(typeName)}, [{string.Join(", ", nameRows)}], [{string.Join(", ", values)}]);");
			adds.Add($"\t\tregistry.Add({fieldName});");
		}

		var fieldLines = fields.Count == 0 ?
			string.Empty :
			string.Join("\n", fields);
		var addLines = adds.Count == 0 ?
			string.Empty :
			string.Join("\n", adds);

		StringBuilder sb = new();
		sb.AppendCSharp(
			$$"""
			// <auto-generated/>
			#nullable enable
			namespace {{rootNamespace}}.NorseXmlShapes;

			#pragma warning disable CS1591 // Generated Futhark enum name registration: no XML doc comments.
			/// <summary>Generated by Norse.Infrastructure.Web.Server.Generator.Xml — one name/value table per enum type reachable from this compilation's facade controllers.</summary>
			internal static class NorseEnumNameRegistration
			{
			{{fieldLines}}

				public static {{XmlNs}}.EnumNameRegistry Build()
				{
					var registry = new {{XmlNs}}.EnumNameRegistry();
			{{addLines}}
					return registry;
				}
			}
			#pragma warning restore CS1591
			""");
		return sb.ToString();
	}
}
