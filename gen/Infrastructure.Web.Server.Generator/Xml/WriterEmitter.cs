using System.Text;
using Norse.Abstractions.Emit;

namespace Norse.Infrastructure.Web.Server.Generator.Xml;

/// <summary>
///     Emits the canonical Futhark XML writer for one contract shape (design spec §6): declaration-order
///     attributes then declaration-order child elements, null scalars omitted, <c>Result&lt;T&gt;</c>
///     unwrap-on-success (a failed or default <c>Result&lt;T&gt;</c> throws — the same platform-wide
///     wording the JSON and gRPC legs use), enum values rendered through the shared runtime
///     <c>EnumLexical.Format</c>/<c>EnumNameTable</c> mechanism (Task 8) — never a per-shape switch — a
///     <c>[Flags]</c> member rendered as repeated governed-name child elements against that same table
///     (amendment 2026-08-09, <see cref="WriteFlags" />) rather than an attribute, and
///     recursion into nested/collection complex members via their own generated shape classes — never a
///     second writer, one recursive projection reused as both "the root" and "a fragment," which is
///     exactly why this method never calls <c>WriteStartDocument</c>: the XML declaration is a
///     whole-document fact the caller's <c>XmlWriterSettings</c> controls (Task 9), not something a
///     per-type <c>Write</c> method can know about itself.
/// </summary>
/// <remarks>
///     <b>Reader emission is composed here too, as of Task 7.</b> <c>IXmlShape&lt;T&gt;</c> declares
///     <c>Read</c>/<c>ReadObject</c> alongside <c>Write</c>/<c>WriteObject</c>, and <see cref="Emit" />
///     produces the single class implementing all four: the writer body stays exactly as this type builds
///     it below, while the presence-aware, accumulating reader body (design spec §8) comes from
///     <see cref="ReaderEmitter" /> — sharing this type's per-member wire-name arrays and, as of Task 8,
///     the same <see cref="EnumTableReference" /> into the generated <c>NorseEnumNameRegistration</c> class
///     rather than either emitter building a table of its own. One emitted file, one class, both
///     directions — never a second writer and never a second reader.
/// </remarks>
static class WriterEmitter
{
	const string XmlNs = "global::Norse.Infrastructure.Web.Server.Xml";

	public static string Emit(string rootNamespace, ShapeModel shape)
	{
		var shortName = ShortName(shape.TypeName);
		var className = $"{shortName}XmlShape";

		var attributeWrites = WriteAttributes(shape, rootNamespace);
		var childWrites = WriteChildren(rootNamespace, shape);
		var fieldDeclarations = FieldDeclarations(shape);

		var readerFieldDeclarations = ReaderEmitter.FieldDeclarations(shape);
		var readMethod = ReaderEmitter.ReadMethod(rootNamespace, shape);

		StringBuilder sb = new();
		sb.AppendCSharp(
			$$"""
			// <auto-generated/>
			#nullable enable
			namespace {{rootNamespace}}.NorseXmlShapes;

			#pragma warning disable CS1591 // Generated Futhark XML shape: no XML doc comments.
			/// <summary>Generated by Norse.Infrastructure.Web.Server.Generator.Xml — canonical Futhark XML reader/writer for <see cref="{{shape.TypeName}}"/>.</summary>
			internal sealed class {{className}} : {{XmlNs}}.IXmlShape<{{shape.TypeName}}>
			{
				internal static readonly {{className}} Instance = new();

				static readonly string[] _rootNames = {{NamesLiteral(shape.WireNames)}};
			{{fieldDeclarations}}
			{{readerFieldDeclarations}}
				public global::System.Type ContractType => typeof({{shape.TypeName}});

				public string RootName({{XmlNs}}.XmlCaseStyle style) =>
					_rootNames[(int)style];

				public void WriteObject(global::System.Xml.XmlWriter writer, object value, {{XmlNs}}.XmlCaseStyle style) =>
					Write(writer, ({{shape.TypeName}})value, style);

				public void Write(global::System.Xml.XmlWriter writer, {{shape.TypeName}} value, {{XmlNs}}.XmlCaseStyle style)
				{
					writer.WriteStartElement(_rootNames[(int)style]);
			{{attributeWrites}}
			{{childWrites}}
					writer.WriteEndElement();
				}

			{{readMethod}}

				public object? ReadObject(global::System.Xml.XmlReader reader, {{XmlNs}}.XmlCaseStyle style, {{XmlNs}}.XmlReadContext context) =>
					Read(reader, style, context);
			}
			#pragma warning restore CS1591
			""");
		return sb.ToString();
	}

	/// <summary>
	///     Dispatches a scalar member's already-unwrapped value expression to its §7 lexical form.
	///     <c>SymbolDisplayFormat.FullyQualifiedFormat</c>'s two rendering shapes are load-bearing
	///     here and were verified empirically (a throwaway Roslyn probe), not assumed: special/keyword
	///     types (<c>string</c>/<c>decimal</c>/<c>int</c>/<c>bool</c>/…) render as bare keywords with no
	///     <c>global::</c> prefix; every other scalar type (<c>Guid</c>/<c>DateTime</c>/<c>DateOnly</c>/
	///     <c>TimeOnly</c>/<c>TimeSpan</c>/<c>DateTimeOffset</c>/enums) renders fully <c>global::</c>-qualified.
	/// </summary>
	static string FormatExpression(MemberModel member, string valueExpression, string rootNamespace)
	{
		if (member.EnumValues.Count > 0)
			return EnumFormatCall(member, valueExpression, rootNamespace);

		return member.ScalarTypeName switch
		{
			"string" => valueExpression,
			"bool" or "decimal" or "double" or "float" or "char" => $"{XmlNs}.XmlLexical.Format({valueExpression})",
			"global::System.Guid" or "global::System.DateTime" or "global::System.DateTimeOffset" or
				"global::System.DateOnly" or "global::System.TimeOnly" or "global::System.TimeSpan" =>
				$"{XmlNs}.XmlLexical.Format({valueExpression})",
			// Integral types carry no XmlLexical overload — deliberate, per the plan's own Task 2
			// interface comment: "generated code calls value.ToString(CultureInfo.InvariantCulture)
			// directly." Invariant ToString on any integral CLR type already IS the pinned §7 wire
			// form, with no exception-throwing edge case (unlike decimal/double/float) to justify a
			// wrapper — this is not a gap in Task 2's XmlLexical, it's documented, decided behavior.
			"sbyte" or "byte" or "short" or "ushort" or "int" or "uint" or "long" or "ulong" =>
				$"{valueExpression}.ToString(global::System.Globalization.CultureInfo.InvariantCulture)",
			_ => throw new InvalidOperationException(
				$"WriterEmitter has no lexical dispatch for scalar type '{member.ScalarTypeName}' on member '{member.ClrName}' — the closed taxonomy (ClosureWalker.IsSupportedScalar) and this switch have drifted apart.")
		};
	}

	/// <summary>
	///     Renders an enum member's write through the shared runtime mechanism — <c>EnumLexical.Format</c>
	///     against the one <see cref="EnumTableReference" /> the generated <c>NorseEnumNameRegistration</c>
	///     class declares for this enum type, generic-inferred from <paramref name="valueExpression" />'s
	///     own type (never an explicit type argument — <c>Format</c>'s <c>TEnum value</c> parameter makes
	///     inference unambiguous, unlike <see cref="ReaderEmitter" />'s <c>Parse</c> call, which has no
	///     parameter of type <c>TEnum</c> and must specify one).
	/// </summary>
	static string EnumFormatCall(MemberModel member, string valueExpression, string rootNamespace) =>
		$"{XmlNs}.EnumLexical.Format({EnumTableReference(rootNamespace, member.ScalarTypeName!)}, {valueExpression}, (int)style)";

	/// <summary>
	///     The fully-qualified reference to one enum type's shared <c>EnumNameTable</c> field on the
	///     generated <c>NorseEnumNameRegistration</c> class (<see cref="RegistrationEmitter" />) — the one
	///     place per host compilation each enum's table is declared, so every shape referencing the same
	///     enum type (and the registry <see cref="RegistrationEmitter" /> builds for the JSON/OpenAPI legs)
	///     all read the exact same instance, never a per-shape copy.
	/// </summary>
	internal static string EnumTableReference(string rootNamespace, string enumTypeName) =>
		$"global::{rootNamespace}.NorseXmlShapes.NorseEnumNameRegistration.{SafeIdentifier(enumTypeName)}Table";

	static string FieldDeclarations(ShapeModel shape)
	{
		List<string> lines = [];
		foreach (var member in shape.Members.Where(m => m.Kind == MemberKind.Scalar))
			lines.Add(member.IsFlagsEnum ?
				$"\tstatic readonly string[] _{member.ClrName}ElementNames = {NamesLiteral(member.WireNames)};" :
				$"\tstatic readonly string[] _{member.ClrName}AttrNames = {NamesLiteral(member.WireNames)};");

		return lines.Count == 0 ?
			string.Empty :
			string.Join("\n", lines);
	}

	static string WriteAttributes(ShapeModel shape, string rootNamespace)
	{
		List<string> lines = [];
		foreach (var member in shape.Members.Where(m => m is { Kind: MemberKind.Scalar, IsFlagsEnum: false }))
			lines.Add(WriteAttribute(member, rootNamespace));

		return lines.Count == 0 ?
			string.Empty :
			string.Join("\n", lines);
	}

	static string WriteAttribute(MemberModel member, string rootNamespace)
	{
		var attrNames = $"_{member.ClrName}AttrNames[(int)style]";

		// Result<T> unwraps on success — the only illegal outbound state is a failure or a defaulted
		// value (TryGetValue(out Success<T>) returns false for both, in one check), matching the
		// pinned platform-wide wording (ResultSerializers.IllegalWriteMessage, the JSON converters'
		// own literal). No truncation concern here (contrast the old always-throw shape this restores
		// over): the throw sits behind a conditional, so every later statement in Write stays reachable
		// regardless of which member throws.
		if (member is { IsResultWrapped: true, IsNullable: true })
		{
			// Explicit HasValue/.Value, not `is { } x` — a `Nullable<T>` not-null property pattern
			// normally narrows to T, but against Result<T>?'s [Union]-marked T (C# 15 preview unions),
			// the narrowed variable mistypes as `object`. HasValue/.Value are ordinary Nullable<T>
			// members, untouched by union pattern-matching restrictions.
			var wrapperVar = $"{member.ClrName}Wrapper";
			var unwrapVar = UnwrapVar(member);
			return
				$"\t\tif (value.{member.ClrName}.HasValue)\n" +
				"\t\t{\n" +
				$"\t\t\tvar {wrapperVar} = value.{member.ClrName}.Value;\n" +
				$"\t\t\tif (!{wrapperVar}.TryGetValue(out global::Norse.Primitives.Success<{member.ScalarTypeName}> {unwrapVar}))\n" +
				"\t\t\t\tthrow new global::System.InvalidOperationException(\"a failed or default Result<T> is illegal to write\");\n" +
				$"\t\t\twriter.WriteAttributeString({attrNames}, {FormatExpression(member, $"{unwrapVar}.Value", rootNamespace)});\n" +
				"\t\t}";
		}

		if (member is { IsResultWrapped: true, IsNullable: false })
		{
			var unwrapVar = UnwrapVar(member);
			return
				$"\t\tif (!value.{member.ClrName}.TryGetValue(out global::Norse.Primitives.Success<{member.ScalarTypeName}> {unwrapVar}))\n" +
				"\t\t\tthrow new global::System.InvalidOperationException(\"a failed or default Result<T> is illegal to write\");\n" +
				$"\t\twriter.WriteAttributeString({attrNames}, {FormatExpression(member, $"{unwrapVar}.Value", rootNamespace)});";
		}

		if (member is { IsResultWrapped: false, IsNullable: true })
		{
			var rawVar = $"{member.ClrName}Raw";
			return
				$"\t\tif (value.{member.ClrName} is {{ }} {rawVar})\n" +
				$"\t\t\twriter.WriteAttributeString({attrNames}, {FormatExpression(member, rawVar, rootNamespace)});";
		}

		return
			$"\t\twriter.WriteAttributeString({attrNames}, {FormatExpression(member, $"value.{member.ClrName}", rootNamespace)});";
	}

	/// <summary>
	///     The local that captures a Result-wrapped member's unwrapped success case — <c>__{camelClrName}</c>, e.g.
	///     <c>__limit</c> for a member named <c>Limit</c>.
	/// </summary>
	static string UnwrapVar(MemberModel member) =>
		$"__{char.ToLowerInvariant(member.ClrName[0])}{member.ClrName.Substring(1)}";

	static string WriteChildren(string rootNamespace, ShapeModel shape)
	{
		List<string> lines = [];
		foreach (var member in shape.Members.Where(m => m.Kind != MemberKind.Scalar || m.IsFlagsEnum))
			lines.Add(member.IsFlagsEnum ?
				WriteFlags(rootNamespace, member) :
				member.Kind == MemberKind.Collection ?
					WriteCollection(rootNamespace, member) :
					WriteComplex(rootNamespace, member));

		return lines.Count == 0 ?
			string.Empty :
			string.Join("\n", lines);
	}

	/// <summary>
	///     Renders a flags member's write as repeated governed-name child elements (amendment 2026-08-09) —
	///     never attributes: the set bits decompose in the enum table's member-declaration order, each
	///     single-bit member present emitting one member-named element with the bit's governed name as text
	///     content, via <see cref="FlagsDecomposition" />. The <c>Result&lt;T&gt;</c>/nullable prologue combos
	///     mirror <see cref="WriteAttribute" />'s exactly, pinned message included.
	/// </summary>
	static string WriteFlags(string rootNamespace, MemberModel member)
	{
		if (member is { IsResultWrapped: true, IsNullable: true })
		{
			var wrapperVar = $"{member.ClrName}Wrapper";
			var unwrapVar = UnwrapVar(member);
			return
				$$"""
						if (value.{{member.ClrName}}.HasValue)
						{
							var {{wrapperVar}} = value.{{member.ClrName}}.Value;
							if (!{{wrapperVar}}.TryGetValue(out global::Norse.Primitives.Success<{{member.ScalarTypeName}}> {{unwrapVar}}))
								throw new global::System.InvalidOperationException("a failed or default Result<T> is illegal to write");
				{{FlagsDecomposition(rootNamespace, member, $"{unwrapVar}.Value", indent: "\t\t\t")}}
						}
				""";
		}

		if (member is { IsResultWrapped: true, IsNullable: false })
		{
			var unwrapVar = UnwrapVar(member);
			return
				$$"""
						if (!value.{{member.ClrName}}.TryGetValue(out global::Norse.Primitives.Success<{{member.ScalarTypeName}}> {{unwrapVar}}))
							throw new global::System.InvalidOperationException("a failed or default Result<T> is illegal to write");
				{{FlagsDecomposition(rootNamespace, member, $"{unwrapVar}.Value", indent: "\t\t")}}
				""";
		}

		if (member is { IsResultWrapped: false, IsNullable: true })
		{
			var rawVar = $"{member.ClrName}Raw";
			return
				$$"""
						if (value.{{member.ClrName}} is { } {{rawVar}})
						{
				{{FlagsDecomposition(rootNamespace, member, rawVar, indent: "\t\t\t")}}
						}
				""";
		}

		return FlagsDecomposition(rootNamespace, member, $"value.{member.ClrName}", indent: "\t\t");
	}

	/// <summary>
	///     The decomposition core <see cref="WriteFlags" /> splices behind its prologue combos: the legality
	///     gate first — any set bit outside the build-time mask of the table's nonzero single-bit member
	///     values (composite/aggregate members contribute nothing to it) is illegal to write and throws
	///     before a single element is written — then one table pass in member-declaration order, emitting
	///     each single-bit member still present in the remaining bits and clearing as it goes, so an alias
	///     member (two names, one value) emits its first-declared name only. The zero value walks the loop
	///     without emitting: no elements is the wire's natural zero.
	/// </summary>
	static string FlagsDecomposition(string rootNamespace, MemberModel member, string valueExpression, string indent)
	{
		var table = EnumTableReference(rootNamespace, member.ScalarTypeName!);
		var camel = $"{char.ToLowerInvariant(member.ClrName[0])}{member.ClrName.Substring(1)}";
		var bitsVar = $"__{camel}Bits";
		var indexVar = $"__{camel}Index";
		var flagVar = $"__{camel}Flag";
		var mask = $"unchecked((long)0x{SingleBitMask(member.EnumValues):X}UL)";
		var bitsExpression = BitsExpression(member, valueExpression);
		// The emitted throw's table hole rides parenthesized — an interpolation hole in the EMITTED
		// interpolated string ends its expression at the first top-level ':', so a bare global::-qualified
		// reference would parse as a format clause there.
		return
			$$"""
			{{indent}}if (({{bitsExpression}} & ~{{mask}}) != 0L)
			{{indent}}	throw new global::System.InvalidOperationException($"'{{{valueExpression}}}' carries bits with no single-bit member of '{({{table}}.EnumType)}' and is illegal to write.");
			{{indent}}var {{bitsVar}} = {{bitsExpression}};
			{{indent}}for (var {{indexVar}} = 0; {{indexVar}} < {{table}}.Count; {{indexVar}}++)
			{{indent}}{
			{{indent}}	var {{flagVar}} = {{table}}.Value({{indexVar}});
			{{indent}}	if ({{flagVar}} == 0L || ({{flagVar}} & ({{flagVar}} - 1L)) != 0L || ({{bitsVar}} & {{flagVar}}) != {{flagVar}})
			{{indent}}		continue;
			{{indent}}	writer.WriteElementString(_{{member.ClrName}}ElementNames[(int)style], {{table}}.Name({{indexVar}}, (int)style));
			{{indent}}	{{bitsVar}} &= ~{{flagVar}};
			{{indent}}}
			""";
	}

	/// <summary>
	///     The emitted expression projecting a flags value into the shared 64-bit table representation —
	///     zero-extending signed 1/2/4-byte underlying types through the unsigned same-width cast so the
	///     result matches the zero-extended table values (<c>ClosureWalker.ToBits</c>, the build-time twin
	///     of the runtime <c>EnumLexical.ToBits</c> law). A bare <c>(long)</c> cast sign-extends: an
	///     int-backed <c>1 &lt;&lt; 31</c> member would land at 0xFFFFFFFF80000000, trip the legality mask,
	///     and throw for a perfectly writable value. The unsigned/8-byte underlying types need no
	///     intermediate cast — their <c>(long)</c> conversion already carries the bits identically.
	/// </summary>
	static string BitsExpression(MemberModel member, string valueExpression) =>
		member.EnumUnderlyingTypeName switch
		{
			"sbyte" => $"unchecked((long)(byte){valueExpression})",
			"short" => $"unchecked((long)(ushort){valueExpression})",
			"int" => $"unchecked((long)(uint){valueExpression})",
			_ => $"unchecked((long){valueExpression})"
		};

	/// <summary>
	///     The union of the table's nonzero single-bit member values — the exact set of bits a flags value
	///     may legally carry onto the wire, computed at generation time from the same
	///     <see cref="EnumValueModel" /> table the registration emits.
	/// </summary>
	static long SingleBitMask(EquatableArray<EnumValueModel> values)
	{
		var mask = 0L;
		foreach (var value in values)
			if (value.Value != 0 && (value.Value & (value.Value - 1)) == 0)
				mask |= value.Value;

		return mask;
	}

	static string WriteCollection(string rootNamespace, MemberModel member)
	{
		var itemShape = $"global::{rootNamespace}.NorseXmlShapes.{ShortName(member.ComplexTypeName!)}XmlShape";
		var itemVar = $"{member.ClrName}Item";
		// Collections are always non-null, empty when absent (spec §5.9) — the null-coalesce is a
		// defensive no-op for a conforming contract and a safe zero-elements fallback for a nullable-
		// reference-annotated collection member, which the shape law doesn't structurally forbid.
		return
			$"\t\tforeach (var {itemVar} in value.{member.ClrName} ?? [])\n" +
			$"\t\t\t{itemShape}.Instance.Write(writer, {itemVar}, style);";
	}

	static string WriteComplex(string rootNamespace, MemberModel member)
	{
		var memberShape = $"global::{rootNamespace}.NorseXmlShapes.{ShortName(member.ComplexTypeName!)}XmlShape";
		if (member.IsNullable)
		{
			var nestedVar = $"{member.ClrName}Nested";
			return
				$"\t\tif (value.{member.ClrName} is {{ }} {nestedVar})\n" +
				$"\t\t\t{memberShape}.Instance.Write(writer, {nestedVar}, style);";
		}

		return $"\t\t{memberShape}.Instance.Write(writer, value.{member.ClrName}, style);";
	}

	/// <summary>
	///     The unqualified type name a fully-qualified <c>global::</c>-prefixed name ends with — also the generated
	///     class's <c>{ShortName}XmlShape</c> prefix and the source-hint-name base <see cref="XmlShapeGenerator" /> uses.
	/// </summary>
	internal static string ShortName(string fullyQualifiedName)
	{
		var withoutPrefix = fullyQualifiedName.StartsWith("global::", StringComparison.Ordinal) ?
			fullyQualifiedName.Substring("global::".Length) :
			fullyQualifiedName;
		var lastDot = withoutPrefix.LastIndexOf('.');
		return lastDot < 0 ?
			withoutPrefix :
			withoutPrefix.Substring(lastDot + 1);
	}

	/// <summary>
	///     A fully-qualified name, flattened into a legal C# identifier fragment — the shared naming scheme both this
	///     emitter's <see cref="EnumTableReference" /> and <see cref="RegistrationEmitter" />'s field declarations use, so the
	///     two sides always agree on one enum type's field name without either coordinating with the other beyond calling this
	///     same method.
	/// </summary>
	internal static string SafeIdentifier(string fullyQualifiedName)
	{
		var withoutPrefix = fullyQualifiedName.StartsWith("global::", StringComparison.Ordinal) ?
			fullyQualifiedName.Substring("global::".Length) :
			fullyQualifiedName;
		return withoutPrefix.Replace('.', '_').Replace('<', '_').Replace('>', '_');
	}

	internal static string NamesLiteral(EquatableArray<string> names)
	{
		List<string> quoted = [];
		for (var i = 0; i < names.Count; i++)
			quoted.Add(Quote(names[i]));
		return $"[{string.Join(", ", quoted)}]";
	}

	internal static string Quote(string value) =>
		"\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
